import AppKit
import Combine

struct ClipItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, file }
    var id = UUID()
    var kind: Kind
    var text: String
    var date = Date()
    var pinned = false
}

/// Clipboard history. Watches the pasteboard, skips items that password managers mark
/// as concealed, and keeps only pinned items on disk.
@MainActor
final class ClipboardService: ObservableObject {
    @Published private(set) var items: [ClipItem] = []

    private let notices: NoticeCenter
    private var lastChange = NSPasteboard.general.changeCount
    private var bag = Set<AnyCancellable>()
    private let limit = 40
    private let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    private let file: URL = {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Blob", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir.appendingPathComponent("clipboard-pinned.json")
    }()

    init(notices: NoticeCenter) {
        self.notices = notices
        if let data = try? Data(contentsOf: file), let pinned = try? JSONDecoder().decode([ClipItem].self, from: data) {
            items = pinned
        }
    }

    func start() {
        Timer.publish(every: 0.6, on: .main, in: .common).autoconnect()
            .sink { [weak self] _ in self?.poll() }
            .store(in: &bag)
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard ModuleID.clipboard.isEnabled else { return }
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: skipTypes) else { return }

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            insert(ClipItem(kind: .file, text: urls.map(\.path).joined(separator: "\n")))
        } else if let string = pb.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            insert(ClipItem(kind: .text, text: string))
        }
    }

    private func insert(_ item: ClipItem) {
        if let existing = items.firstIndex(where: { $0.text == item.text && $0.kind == item.kind }) {
            var moved = items.remove(at: existing)
            moved.date = Date()
            items.insert(moved, at: 0)
        } else {
            items.insert(item, at: 0)
        }
        // Drop the oldest unpinned items past the limit.
        while items.count > limit, let last = items.lastIndex(where: { !$0.pinned }) {
            items.remove(at: last)
        }
    }

    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if item.kind == .file {
            pb.writeObjects(item.text.split(separator: "\n").map { URL(fileURLWithPath: String($0)) as NSURL })
        } else {
            pb.setString(item.text, forType: .string)
        }
        lastChange = pb.changeCount
        insert(item)
        notices.message("checkmark", "Copied", duration: 1.2)
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[i].pinned.toggle()
        savePinned()
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        savePinned()
    }

    func clearUnpinned() { items.removeAll { !$0.pinned } }

    private func savePinned() {
        if let data = try? JSONEncoder().encode(items.filter(\.pinned)) { try? data.write(to: file, options: .atomic) }
    }
}
